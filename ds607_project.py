"""#KS Test

For Revenue:

*   Null hypothesis (H₀): The distribution of revenue is the same for public and private firms in that year. $$F_{\text{public}}(x) = F_{\text{private}}(x) \quad \text{for all } x$$
*   Alternative hypothesis (H₁): The distributions differ. Formally,$$F_{\text{public}}(x) \neq F_{\text{private}}(x) \quad \text{for at least one value of } x$$

For Total Assets:

*   Null hypothesis (H₀): The distribution of total assets is the same for public and private firms in that year. Formally, $$F_{\text{public}}(x) = F_{\text{private}}(x) \quad \text{for all } x$$

*   Alternative hypothesis (H₁): The distributions differ. Formally, $$F_{\text{public}}(x) \neq F_{\text{private}}(x) \quad \text{for at least one value of } x$$
"""

measures = {
    'Operating revenue (Turnover) bn USD': 'Revenue',
    'Total assets bn USD': 'Total assets',
}

ks_results = []
for year in range(2021, 2026):
    for col, label in measures.items():
        # Valid values only: strictly positive, non-missing (NaN > 0 is False)
        pub = public.loc[(public['Year'] == year) & (public[col] > 0), col].to_numpy()
        pri = private.loc[(private['Year'] == year) & (private[col] > 0), col].to_numpy()

        res = ks_2samp(pub, pri)  # two-sided by default
        ks_results.append({
            'Year': year,
            'Measure': label,
            'n_public': len(pub),
            'n_private': len(pri),
            'D': round(res.statistic, 4),
            'p_value': res.pvalue,
        })

ks_table = pd.DataFrame(ks_results)
print(ks_table)

"""Every p-value is far below 0.001, so the null is rejected for all 10 tests. The D values are large, around 0.58 to 0.65, which means the public and private distributions are very different. They are also declining slightly over time, so the gap is narrowing, but it remains large.

Because the sample sizes are so unequal (about 479 public firms versus 23,000 to 33,000 private firms), the p-values are very small, and the test will detect even minor differences.

#Bootstrap Annual Median Difference `D`
"""

B = 10_000        # bootstrap replications
SEED = 2026         # fixed seed for reproducibility
CHUNK = 200       # resample in blocks to keep memory bounded
rng = np.random.default_rng(SEED)

measures = {
    'Operating revenue (Turnover) bn USD': 'Revenue',
    'Total assets bn USD': 'Total assets',
}

boot_rows = []
for year in range(2021, 2026):
    for col, label in measures.items():
        # Valid values only: strictly positive, non-missing
        a = public.loc[(public['Year'] == year) & (public[col] > 0), col].to_numpy()
        b = private.loc[(private['Year'] == year) & (private[col] > 0), col].to_numpy()

        point = np.median(a) - np.median(b)

        # Resample each group with replacement, then take the median difference
        boot = np.empty(B)
        for start in range(0, B, CHUNK):
            k = min(CHUNK, B - start)
            boot_a = a[rng.integers(0, len(a), size=(k, len(a)))]
            boot_b = b[rng.integers(0, len(b), size=(k, len(b)))]
            boot[start:start + k] = np.median(boot_a, axis=1) - np.median(boot_b, axis=1)

        ci_low, ci_high = np.percentile(boot, [2.5, 97.5])

        boot_rows.append({
            'Year': year,
            'Measure': label,
            'n_public': len(a),
            'n_private': len(b),
            'M_public': np.median(a),
            'M_private': np.median(b),
            'Difference': point,
            'CI_low_95': ci_low,
            'CI_high_95': ci_high,
        })

boot_table = pd.DataFrame(boot_rows)
print(boot_table.round(4))

"""Every confidence interval is above zero, so the public median is larger than the private median in every year and for both measures. The gap is about 60 million USD for revenue and about 100 million USD for total assets, and it is stable across years.

These medians are for firms with positive values only. The private median is very small because many private firms are tiny, so the medians are sensitive to the zero-value exclusion. Note this in the report.
"""